import { expect, use } from "chai";
import chaiAsPromised from "chai-as-promised";
import fs from "node:fs/promises";
import path from "node:path";

import { ConanPkgManager } from "../src/conan-backend/conan-backend.js";

use(chaiAsPromised);

// Fixtures generated by test/fixtures/cross-platform-tarballs/generate.sh.
// Both package the same mock recipe (cfs_tar_platform_mock/1.0.0), built
// once per `settings.os`, so restoring the "wrong" one deterministically
// reproduces a platform mismatch instead of an ordinary missing-package
// error.
const linuxTarball = path.resolve(
	"./test/data/cross-platform-pkg-linux.tgz"
);
const windowsTarball = path.resolve(
	"./test/data/cross-platform-pkg-windows.tgz"
);
// The tarball that matches this host's own platform, and the one that
// does not. Used so the "happy path" test exercises a real install on
// whichever OS the suite runs on, while the mismatch tests target the
// specific pairing each scenario needs.
const nativeTarball =
	process.platform === "win32" ? windowsTarball : linuxTarball;
const foreignTarball =
	process.platform === "win32" ? linuxTarball : windowsTarball;
const mockPkgRef = {
	name: "cfs_tar_platform_mock",
	version: "1.0.0"
};

// Fixture for the OS-independent case: a package that declares no
// `settings` at all (the same shape as a real CFS package like
// cfs_base_data_models), so its package_id never varies by platform.
// A tarball of it must install on either host.
const genericTarball = path.resolve(
	"./test/data/cross-platform-pkg-generic.tgz"
);
const genericPkgRef = {
	name: "cfs_tar_generic_mock",
	version: "1.0.0"
};

describe("Local tarball install", function () {
	const testCacheDir = path.join(process.cwd(), "test_cache");
	const testConfigDir = path.join(process.cwd(), "test_config");
	const testConanHome = path.join(testCacheDir, "conan");

	let api: ConanPkgManager;

	async function cleanCache() {
		await fs.rm(testCacheDir, { recursive: true, force: true });
		await fs.rm(testConfigDir, { recursive: true, force: true });
	}

	async function setupTest() {
		await fs.cp(
			path.resolve("./src/conan-backend/config"),
			testConfigDir,
			{ recursive: true, force: true }
		);

		api = new ConanPkgManager({
			conanHome: testConanHome,
			indexDir: testCacheDir,
			conanConfigPath: testConfigDir
		});

		await api.init();
	}

	// Each test restores a tarball for the same recipe/version into the
	// shared cache. Purge it before every test so an earlier test's cached
	// binary can never satisfy (or otherwise influence) a later one.
	// `delete` on a wildcard pattern silently skips packages that are
	// still marked installed, so uninstall first.
	async function purgePackage(name: string) {
		try {
			await api.uninstall(name);
		} catch {
			// Not installed - fine.
		}
		try {
			await api.delete(`${name}/*`);
		} catch {
			// Nothing cached - fine.
		}
	}

	async function purgeMockPackages() {
		await purgePackage(mockPkgRef.name);
		await purgePackage(genericPkgRef.name);
	}

	before(cleanCache);
	after(cleanCache);
	before(setupTest);
	beforeEach(purgeMockPackages);

	it("installs a tarball from a path relative to the caller's cwd, not the conan subprocess cwd", async function () {
		// Regression test for the path.resolve() fix in localInstall():
		// _conanCommand always runs the conan subprocess with cwd=indexDir
		// (test_cache here), so a relative path handed straight through
		// would previously resolve against the package cache directory
		// instead of this process's actual working directory, and the
		// install would fail to find the tarball at all.
		const relativeTarball = path.relative(
			process.cwd(),
			nativeTarball
		);
		expect(path.isAbsolute(relativeTarball)).to.be.false;

		await expect(api.localInstall(relativeTarball)).to.be.fulfilled;

		expect(await api.list()).to.deep.include(mockPkgRef);
	});

	it("installs an OS-independent tarball on any host platform", async function () {
		// cfs_tar_generic_mock declares no `settings`, so there is only
		// ever one package_id regardless of host os/arch - unlike
		// cfs_tar_platform_mock, there is no "wrong" tarball to restore
		// here. This is the control case for the two mismatch tests
		// below: it confirms the local-tarball install path does not
		// misclassify an OS-independent package as a platform mismatch.
		await expect(api.localInstall(genericTarball)).to.be.fulfilled;

		expect(await api.list()).to.deep.include(genericPkgRef);
	});

	it("fails with a platform-mismatch message when installing a Windows-built tarball on this Linux host", async function () {
		// The Windows tarball only contains legal-everywhere filenames, so
		// it restores cleanly on Linux; the failure comes purely from
		// os=Windows having no binary that matches a Linux profile. That
		// makes this the one pairing of {tarball, host} that isolates the
		// binary_platform_mismatch classification in error_handling.py
		// from the restore-time failure covered below. The reverse pairing
		// (Windows host installing the Windows tarball) can't produce this
		// error at all, since the binary would match - hence Linux-only.
		if (process.platform !== "linux") {
			this.skip();
		}

		try {
			await api.localInstall(windowsTarball);
			expect.fail(
				"Expected localInstall to reject a Windows-only binary on a Linux host"
			);
		} catch (err) {
			const message =
				err instanceof Error ? err.message : String(err);

			// Classified by the binary_platform_mismatch ErrorPattern.
			expect(message).to.match(
				/No binaries built for os=Linux are available for: cfs_tar_platform_mock\/1\.0\.0/,
				"should report the os mismatch and the package reference"
			);
			expect(message).to.match(
				/These packages were built for a different operating system\./,
				"should explain why no matching binary was found"
			);

			// Wrapped by cfs_local_install with the tarball path and a
			// cleanup hint naming what the restore left behind in the
			// cache, since the recipe/binary are not rolled back on
			// install failure.
			expect(message).to.include(
				`Failed to install from tarball '${windowsTarball}'`
			);
			expect(message).to.match(
				/References cached by the restore: cfs_tar_platform_mock\/1\.0\.0/,
				"should name the references the restore left behind so the user can clean up"
			);
			expect(message).to.include(
				"You may want to delete these references from the cache."
			);
		}
	});

	it("fails during cache restore when installing a Linux-built tarball on Windows", async function () {
		// The Linux tarball contains share/man/man3/App::Cpan.3, a
		// filename with "::" that Linux permits but Windows does not.
		// `conan cache restore` fails extracting it (OSError: [Errno 22]
		// Invalid argument) before cfs_local_install's install step - and
		// before the binary_platform_mismatch classification above even
		// comes into play - so this can only be exercised on a real
		// Windows host/runner. There is no way to simulate an illegal
		// Windows filename on a Linux filesystem, which permits "::".
		if (process.platform !== "win32") {
			this.skip();
		}

		try {
			await api.localInstall(foreignTarball);
			expect.fail(
				"Expected localInstall to reject a tarball containing a Windows-illegal filename"
			);
		} catch (err) {
			const message =
				err instanceof Error ? err.message : String(err);

			// Classified by the illegal_filename_restore ErrorPattern.
			// The raw OSError text ("Errno 22", "Invalid argument") is
			// deliberately not surfaced verbatim - this asserts on the
			// human-readable replacement instead.
			expect(message).to.include(
				"Cannot restore this tarball: it contains a file name that is not valid on this operating system:"
			);
			expect(message).to.include("App::Cpan.3");
			expect(message).to.include(
				"This usually means the tarball was built for a different operating system."
			);
			expect(message).to.include(
				"The cache may now hold a partial extraction of this package; you may want to delete it."
			);
		}
	});
});
