/**
 * Generates the canonical .cfsconfig JSON schema from the `CfsConfig`
 * TypeScript interface in cfs-types (the single source of truth for the
 * .cfsconfig file shape), then writes it both as a standalone JSON file and
 * as a TypeScript module that cfs-lib can import as a runtime object.
 *
 * Keeping the schema in a generated .ts (rather than reading the JSON at
 * runtime) means the CfsConfig class works identically whether it runs from
 * source or from compiled output, without any file-system lookups or
 * packaging steps.
 */

import { createGenerator } from "ts-json-schema-generator";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));

const ROOT_TYPE_NAME = "CfsConfig";

// The type alias holding the single version newly written documents declare.
// `CfsConfig.SchemaVersion` is the wider union of versions the runtime still
// reads, so the generated schema is pinned to this one instead.
const LATEST_VERSION_TYPE_NAME = "CfsConfigLatestSchemaVersion";

const schemaJsonDir = resolve(__dirname, "../src/types/schemas");
const schemaTsDir = resolve(__dirname, "../src/resources/schemas");

/**
 * Reads the schema version a generated schema declares (the `const` on its
 * `CfsConfig.SchemaVersion` property). Each schema is frozen per version, so
 * this drives the per-version file names.
 * @param {object} schema - A schema produced by {@link buildSchema}.
 * @returns {string} The schema version, e.g. "2.1.0".
 */
export function getSchemaVersion(schema) {
	const version =
		schema?.definitions?.[ROOT_TYPE_NAME]?.properties?.SchemaVersion
			?.const;

	if (typeof version !== "string") {
		throw new Error(
			`Generated schema is missing a string ${ROOT_TYPE_NAME}.SchemaVersion const.`
		);
	}

	return version;
}

/**
 * Resolves the `.json` and `.ts` paths a given schema version is written to.
 * @param {string} version - The schema version, e.g. `"2.1.0"`.
 * @returns {{ jsonPath: string, tsPath: string }} The output file paths.
 */
export function schemaPaths(version) {
	return {
		jsonPath: resolve(
			schemaJsonDir,
			`cfsconfig-schema-${version}.json`
		),
		tsPath: resolve(schemaTsDir, `cfsconfig-schema-${version}.ts`)
	};
}

/**
 * Serializes a schema to the exact `.json` file contents (canonical,
 * newline-terminated). Shared with the drift check so both agree on format.
 * @param {object} schema - A schema produced by {@link buildSchema}.
 * @returns {string} The `.json` file contents.
 */
export function renderJson(schema) {
	return `${JSON.stringify(schema, null, 2)}\n`;
}

/**
 * Serializes a schema to the exact `.ts` module contents (the schema embedded
 * as a `const` export). Shared with the drift check so both agree on format.
 * @param {object} schema - A schema produced by {@link buildSchema}.
 * @returns {string} The `.ts` file contents.
 */
export function renderTs(schema) {
	return [
		"/**",
		" *",
		" * Copyright (c) 2026 Analog Devices, Inc.",
		" *",
		' * Licensed under the Apache License, Version 2.0 (the "License");',
		" * you may not use this file except in compliance with the License.",
		" *",
		" */",
		"",
		"// AUTO-GENERATED by scripts/generate-cfsconfig-schema.js",
		"// Do not edit manually. Source of truth: the `CfsConfig` interface in",
		"// cfs-types (packages/cfs-types/src/types/cfs-config.ts).",
		"//",
		"// This is a single, frozen `.cfsconfig` schema version. Register it in",
		"// resources/cfsconfig-schemas.ts to make it available to the runtime.",
		"",
		`export const cfsConfigSchema = ${JSON.stringify(schema, null, 2)} as const;`,
		""
	].join("\n");
}

/**
 * Generates the .cfsconfig JSON schema from the `CfsConfig` TypeScript
 * interface, entirely in memory (nothing is written to disk). Exported so
 * `check-cfsconfig-schema-drift.js` can build the same schema to compare
 * against the checked-in files without duplicating the generator setup.
 */
export function buildSchema() {
	const schema = normalizeGenericDefinitions(
		generateSchemaFor("CfsConfigSchema")
	);

	const rootDefinition = schema.definitions?.[ROOT_TYPE_NAME];
	if (!rootDefinition) {
		throw new Error(
			`Generated schema is missing the "${ROOT_TYPE_NAME}" definition.`
		);
	}

	// Replace the generator's defaults - a draft-07 `$schema` and a
	// `description` pulled from the nearest leading comment (the file's
	// copyright header) - with the metadata this schema has always used.
	// `description` is deleted first so it lands in the same position whether
	// or not the generator produced one.
	schema.$schema = "https://json-schema.org/draft/2020-12/schema";
	schema.title = "CFSConfig Schema";
	delete rootDefinition.description;
	rootDefinition.description = "Schema for the CFSConfig files";

	// `CfsConfig` (like other cfs-types top-level document interfaces) extends
	// `Record<string, unknown>` so it can be passed to generic utilities that
	// expect an index signature. That makes ts-json-schema-generator treat the
	// root object as open (no `additionalProperties: false`). The schema used
	// to validate real .cfsconfig files should stay closed at the root, as it
	// was before this schema was generated, so unexpected/misspelled
	// top-level properties are still caught.
	rootDefinition.additionalProperties = false;

	pinSchemaVersion(schema, rootDefinition);
	applyZephelinInterfaceCompatibility(schema);

	return schema;
}

/**
 * Keeps the published definition names when generating the default generic
 * configuration. Consumer-specific platform contracts must not affect schemas.
 * @param {object} schema - The schema for the default configuration alias.
 * @returns {object} The schema with its original definition names.
 */
function normalizeGenericDefinitions(schema) {
	const names = new Map([
		["CfsConfig<PluginConfig>", ROOT_TYPE_NAME],
		["ConfiguredProject<PluginConfig>", "ConfiguredProject"]
	]);

	for (const name of names.keys()) {
		if (!schema.definitions?.[name]) {
			throw new Error(`Generated schema is missing "${name}".`);
		}
	}

	delete schema.definitions.CfsConfigSchema;
	schema.$ref = `#/definitions/${ROOT_TYPE_NAME}`;
	schema.definitions = Object.fromEntries(
		Object.entries(schema.definitions).map(([name, definition]) => [
			names.get(name) ?? name,
			definition
		])
	);

	const references = new Map(
		[...names].map(([name, target]) => [
			`#/definitions/${encodeURIComponent(name)}`,
			`#/definitions/${target}`
		])
	);

	function rewriteReferences(node) {
		if (node === null || typeof node !== "object") return;
		if (references.has(node.$ref)) {
			node.$ref = references.get(node.$ref);
		}
		for (const value of Object.values(node)) {
			rewriteReferences(value);
		}
	}

	rewriteReferences(schema);
	return schema;
}

/**
 * Builds the in-memory schema for one exported type of the `CfsConfig` source
 * file.
 * @param {string} typeName - The exported type to generate a schema for.
 * @returns {object} The generated schema.
 */
function generateSchemaFor(typeName) {
	const generator = createGenerator({
		path: resolve(
			__dirname,
			"../../cfs-types/src/types/cfs-config.ts"
		),
		tsconfig: resolve(__dirname, "../../cfs-types/tsconfig.json"),
		type: typeName,
		// The source .ts files are type-checked separately as part of the
		// cfs-types build; skipping it here avoids duplicating that work and
		// keeps schema generation fast.
		skipTypeCheck: true
	});

	return generator.createSchema(typeName);
}

/**
 * Reads the single version that {@link LATEST_VERSION_TYPE_NAME} declares.
 * @returns {string} The latest schema version, e.g. `"2.2.0"`.
 * @throws {Error} When the type is not a single string literal.
 */
function readLatestSchemaVersion() {
	const latest = generateSchemaFor(LATEST_VERSION_TYPE_NAME);
	const version =
		latest?.definitions?.[LATEST_VERSION_TYPE_NAME]?.const;

	if (typeof version !== "string") {
		throw new Error(
			`\`${LATEST_VERSION_TYPE_NAME}\` must be a single string literal type, ` +
				"because each generated schema is frozen to exactly one version."
		);
	}

	return version;
}

/**
 * Narrows the root `SchemaVersion` property from the union of versions the
 * runtime accepts down to the single version this schema is frozen to.
 *
 * `CfsConfig.SchemaVersion` has to stay wide in TypeScript so a document read
 * from disk isn't typed as though it were already the latest version. A
 * generated schema, on the other hand, describes one version only - documents
 * declaring an older version are validated against that version's own frozen
 * schema instead.
 * @param {object} schema - The schema being built.
 * @param {object} rootDefinition - The root `CfsConfig` definition.
 * @throws {Error} When the root definition has no `SchemaVersion` property.
 */
function pinSchemaVersion(schema, rootDefinition) {
	const property = rootDefinition.properties?.SchemaVersion;

	if (!property) {
		throw new Error(
			`Generated schema is missing the ${ROOT_TYPE_NAME}.SchemaVersion property.`
		);
	}

	rootDefinition.properties.SchemaVersion = {
		type: "string",
		const: readLatestSchemaVersion(),
		...(property.description
			? { description: property.description }
			: {})
	};

	// The version aliases are only reachable through the property just
	// rewritten, so they would otherwise be left behind as unused definitions.
	delete schema.definitions?.CfsConfigSchemaVersion;
	delete schema.definitions?.[LATEST_VERSION_TYPE_NAME];
}

/**
 * `Zephelin.Interface`/`Port` used to support a conditional requirement
 * ("Port is required when Interface is 'UART'") plus a legacy object shape
 * for `Interface` (`{ Type: "UART" | "USB", Port?: string }`), both of
 * which predate the current flat `CfsConfig`/`Zephelin` TypeScript shape
 * and can't be expressed by that plain interface. Existing/older
 * `.cfsconfig` documents may still use either form, so the validation
 * schema (unlike the TypeScript type, which only needs to describe what
 * this app currently writes) needs to keep accepting both. Graft that
 * back on here, matching the hand-written schema that predates
 * generating this file from `CfsConfig`.
 */
function applyZephelinInterfaceCompatibility(schema) {
	const zephelin = schema.definitions?.Zephelin;
	if (!zephelin) {
		throw new Error(
			'Generated schema is missing the "Zephelin" definition.'
		);
	}

	// `ZephelinInterface` isn't reachable from `CfsConfig` any more (only
	// `ZephelinInterfaceConfig` is), so the generator no longer emits it as
	// a definition. The legacy string-form Interface below still needs it.
	if (!schema.definitions.ZephelinInterface) {
		schema.definitions.ZephelinInterface = {
			type: "string",
			enum: ["UART", "USB"]
		};
	}

	zephelin.properties.Interface = {
		description:
			"Interface used to transfer profiling data i.e. UART",
		oneOf: [
			{
				$comment:
					"Kept for backwards compatibility: Interface as a plain string. Port is supplied via the sibling Port property.",
				$ref: "#/definitions/ZephelinInterface"
			},
			{
				type: "object",
				properties: {
					Type: {
						type: "string",
						description: "The transport type of the interface",
						enum: ["UART", "USB"]
					}
				},
				oneOf: [
					{
						properties: {
							Type: { const: "UART" },
							Port: {
								type: "string",
								description:
									"The name of the UART instance used to transfer profiling data, as specified in the data model."
							}
						},
						required: ["Port"],
						additionalProperties: false
					},
					{
						properties: {
							Type: { const: "USB" }
						},
						additionalProperties: false
					}
				],
				required: ["Type"],
				additionalProperties: false
			}
		]
	};

	zephelin.if = {
		$comment:
			"Backwards compatibility: If the Interface is a string and is 'UART', then the Port property must be present.",
		properties: {
			Interface: { const: "UART" }
		}
	};
	zephelin.then = {
		required: ["Port"]
	};
}

// Only regenerate and write the schema files when this script is run
// directly (`yarn generate-schema`), not when `buildSchema` is imported by
// the drift-check script.
const isMainModule =
	process.argv[1] !== undefined &&
	import.meta.url === pathToFileURL(process.argv[1]).href;

if (isMainModule) {
	const force = process.argv.includes("--force");

	const schema = buildSchema();
	const version = getSchemaVersion(schema);
	const { jsonPath, tsPath } = schemaPaths(version);

	// A released schema version is frozen: refuse to clobber existing files so
	// a schema change forces a version bump (and a new pair of files) rather
	// than silently rewriting history. `--force` is available for correcting a
	// version that has not shipped yet.
	const existing = [jsonPath, tsPath].filter((p) => existsSync(p));

	if (existing.length > 0 && !force) {
		console.error(
			[
				"",
				`[cfs-lib] Schema files for version ${version} already exist:`,
				...existing.map((p) => `  - ${p}`),
				"",
				"Refusing to overwrite a frozen schema version. Bump",
				"`CfsConfig.SchemaVersion` in cfs-types and re-run to generate a new",
				"version, or pass --force to overwrite (only for a version that has",
				"not shipped yet).",
				""
			].join("\n")
		);
		process.exit(1);
	}

	writeFileSync(jsonPath, renderJson(schema));
	writeFileSync(tsPath, renderTs(schema));

	console.log(
		[
			`Generated .cfsconfig schema version ${version}:`,
			`  - ${jsonPath}`,
			`  - ${tsPath}`,
			"",
			"Remember to register the new schema in",
			"src/resources/cfsconfig-schemas.ts."
		].join("\n")
	);
}
