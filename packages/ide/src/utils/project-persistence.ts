import type { ConfiguredProject } from "cfs-types";

/**
 * Applies the peripheral and partition updates produced by System Planner to
 * the projects currently stored in a configuration document.
 *
 * The System Planner's project cache is initialized when the editor opens and
 * can therefore contain template defaults for fields changed later by other
 * tools, such as profiling and AI model configuration. Peripheral persistence
 * owns only `Partitions` and `Peripherals`; all other fields must come from
 * the current document.
 *
 * @param persistedProjects Projects currently stored in the configuration.
 * @param peripheralUpdates Project updates generated by peripheral persistence.
 * @returns Projects with only peripheral-owned fields updated.
 */
export function mergePeripheralProjectUpdates(
  persistedProjects: ConfiguredProject[],
  peripheralUpdates: ConfiguredProject[]
): ConfiguredProject[] {
  const updatesByProjectId = new Map(
    peripheralUpdates.map((project) => [project.ProjectId, project])
  );

  const mergedProjects = persistedProjects.map((persistedProject) => {
    const update = updatesByProjectId.get(persistedProject.ProjectId);

    if (!update) {
      return persistedProject;
    }

    return {
      ...persistedProject,
      Partitions: update.Partitions,
      Peripherals: update.Peripherals,
    };
  });

  return mergedProjects;
}
